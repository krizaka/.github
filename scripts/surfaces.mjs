#!/usr/bin/env node
// « Done » covers every surface of the product (krizaka/.github#439; AGENT-RULES « Open PRs before new work », last bullet).
//
//   node scripts/surfaces.mjs write            regenerate the feature templates from docs/standards/surfaces.json
//   node scripts/surfaces.mjs verify           fail when a generated template is out of date
//   node scripts/surfaces.mjs check --repo <owner/repo> --issue <n>      the closing check: reopen a closed `feature` issue that misses a surface
//   node scripts/surfaces.mjs sweep --owners orazaka,yomizaka,akinaza [--hours 3]   the same check over recently closed issues
//
// The pure rules are exported and tested (tests/surfaces.test.mjs); the network part is at the bottom.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const MARKER = "<!-- surfaces-check -->";
const BEGIN = "# surfaces:begin (generated by scripts/surfaces.mjs from docs/standards/surfaces.json, do not edit)";
const END = "# surfaces:end";
const CONFIG = "docs/standards/surfaces.json";
const BASE = ".github/ISSUE_TEMPLATE/feature_request.yml";
const OUT = (product) => `docs/standards/surfaces/feature_request.${product}.yml`;

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export const loadConfig = (path = CONFIG) => JSON.parse(readFileSync(path, "utf8")).products;

/** The product of a repository: the GitHub owner of its repositories (`orazaka/orazaka-cli` -> orazaka), or null. */
export function productOf(repoFullName, products) {
  const owner = repoFullName.split("/")[0];
  return products[owner] ? owner : null;
}

/** Is it a feature issue? The `type:feature` label or the org issue type « Feature ». */
export const isFeature = (issue) => issue.type?.name === "Feature" || (issue.labels ?? []).some((l) => (l.name ?? l) === "type:feature");

const checklist = (surfaces) => surfaces.map((s) => `- [ ] ${s.label} — `).join("\n");

const HOW = "Tick each surface with the PR that ships it (`- [x] Web — owner/repo#12`) or mark it `- [x] Web — n/a — <reason>`. An issue with a surface left open or without a PR or a reason is reopened when closed.";

/** The textarea of the template: one product's checklist, or every product's (the org default, to keep the product's own). */
export function surfacesBlock(products, product) {
  const chosen = product ? { [product]: products[product] } : products;
  const value = Object.values(chosen)
    .map((p) => (product ? checklist(p.surfaces) : `${p.title}\n${checklist(p.surfaces)}`))
    .join("\n\n");
  const indented = value
    .split("\n")
    .map((l) => (l ? `        ${l}` : ""))
    .join("\n");
  return [
    BEGIN,
    "  - type: textarea",
    "    id: surfaces",
    "    attributes:",
    "      label: Surfaces",
    `      description: ${JSON.stringify(product ? HOW : `${HOW} Keep the block of your product, delete the others.`)}`,
    "      value: |",
    indented,
    "    validations:",
    "      required: true",
    END,
  ].join("\n");
}

/** The template with its generated block replaced (or appended when the base has none yet). */
export function withSurfaces(base, products, product) {
  const block = surfacesBlock(products, product);
  const re = new RegExp(`${escapeRe(BEGIN)}[\\s\\S]*?${escapeRe(END)}`);
  return re.test(base) ? base.replace(re, () => block) : `${base.replace(/\s*$/, "")}\n${block}\n`;
}

/** The checklist lines of the « Surfaces » section of an issue body (a `###` or `##` heading up to the next heading). */
export function surfacesSection(body = "") {
  const m = /^#{2,3}\s*Surfaces\s*$/im.exec(body);
  if (!m) return null;
  const rest = body.slice(m.index + m[0].length);
  const next = /^#{1,3}\s/m.exec(rest);
  return (next ? rest.slice(0, next.index) : rest)
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => /^[-*]\s*\[[ xX]\]/.test(l));
}

const PR_REF = /(?:^|[\s(])(?:[\w.-]+\/[\w.-]+)?#\d+\b|github\.com\/[\w.-]+\/[\w.-]+\/pull\/\d+/;
const NA = /\bn\/a\b\s*[—–:-]+\s*\S.{2,}/i;

/** What is wrong with the surfaces of an issue of this product: an empty list means done on every surface. */
export function surfaceProblems(body, surfaces) {
  const lines = surfacesSection(body);
  if (!lines) return [`no « Surfaces » checklist (${surfaces.map((s) => s.label).join(", ")})`];
  const problems = [];
  for (const s of surfaces) {
    const re = new RegExp(`^[-*]\\s*\\[( |x|X)\\]\\s*${escapeRe(s.label)}\\b`, "i");
    const line = lines.find((l) => re.test(l));
    if (!line) problems.push(`${s.label}: missing from the checklist`);
    else if (/\[ \]/.test(line)) problems.push(`${s.label}: not ticked`);
    else if (!PR_REF.test(line) && !NA.test(line)) problems.push(`${s.label}: ticked without a PR link or « n/a — reason »`);
  }
  return problems;
}

/** The verdict for one closed issue of a repository: skipped (not a feature, not a product, still open, not planned) or ok / problems. */
export function evaluate(issue, repoFullName, products) {
  const product = productOf(repoFullName, products);
  const skip = !product || issue.pull_request || issue.state !== "closed" || issue.state_reason === "not_planned" || !isFeature(issue);
  if (skip) return { skipped: true, ok: true, problems: [] };
  const problems = surfaceProblems(issue.body, products[product].surfaces);
  return { skipped: false, ok: problems.length === 0, product, problems };
}

export const reopenComment = (problems) =>
  [
    MARKER,
    "Reopened: « done » covers every surface of the product (krizaka/.github#439). To close this feature, fix the « Surfaces » checklist:",
    "",
    ...problems.map((p) => `- ${p}`),
    "",
    "Each surface is ticked with the PR that ships it or marked `n/a — <reason>`. A missing surface is an issue in the same lane.",
  ].join("\n");

async function api(path, { method = "GET", body } = {}) {
  const auth = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  const res = await fetch(`https://api.github.com/${path}`, {
    method,
    headers: { accept: "application/vnd.github+json", ...(auth ? { authorization: `Bearer ${auth}` } : {}) },
    ...(body ? { body: JSON.stringify(body) } : {}),
    signal: AbortSignal.timeout(20000),
  });
  if (!res.ok) throw new Error(`${method} ${path}: ${res.status}`);
  return res.json();
}
const flag = (argv, name) => argv[argv.indexOf(name) + 1];

async function enforce(repo, issue, products) {
  const v = evaluate(issue, repo, products);
  if (v.skipped) return console.log(`${repo}#${issue.number}: skipped`);
  if (v.ok) return console.log(`${repo}#${issue.number}: ok (${v.product})`);
  await api(`repos/${repo}/issues/${issue.number}/comments`, { method: "POST", body: { body: reopenComment(v.problems) } });
  await api(`repos/${repo}/issues/${issue.number}`, { method: "PATCH", body: { state: "open" } });
  console.log(`${repo}#${issue.number}: reopened, ${v.problems.join("; ")}`);
}

async function check(argv) {
  const repo = flag(argv, "--repo");
  await enforce(repo, await api(`repos/${repo}/issues/${Number(flag(argv, "--issue"))}`), loadConfig());
}

async function sweep(argv) {
  const products = loadConfig();
  const owners = (flag(argv, "--owners") ?? Object.keys(products).join(",")).split(",");
  const since = new Date(Date.now() - Number(argv.includes("--hours") ? flag(argv, "--hours") : 3) * 3_600_000).toISOString();
  for (const owner of owners) {
    let repos;
    try {
      repos = (await api(`orgs/${owner}/repos?per_page=100&type=all`)).filter((r) => !r.archived);
    } catch (e) {
      console.log(`::warning title=Surfaces::${owner} not reachable (${e.message})`);
      continue;
    }
    for (const r of repos) {
      const issues = await api(`repos/${owner}/${r.name}/issues?state=closed&since=${since}&per_page=100`);
      for (const i of issues.filter((x) => Date.parse(x.closed_at) >= Date.parse(since))) await enforce(`${owner}/${r.name}`, i, products);
    }
  }
}

function templates(mode) {
  const products = loadConfig();
  const base = readFileSync(BASE, "utf8");
  const wanted = [[BASE, withSurfaces(base, products)], ...Object.keys(products).map((p) => [OUT(p), withSurfaces(base, products, p)])];
  let stale = 0;
  for (const [path, text] of wanted) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {
      /* not generated yet */
    }
    if (mode === "write") writeFileSync(path, text);
    else if (current !== text) {
      stale++;
      console.error(`out of date: ${path}`);
    }
  }
  if (stale) {
    console.error("run: node scripts/surfaces.mjs write");
    process.exit(1);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [cmd, ...rest] = process.argv.slice(2);
  const run = { write: () => templates("write"), verify: () => templates("verify"), check, sweep }[cmd];
  if (!run) {
    console.error("usage: surfaces.mjs write | verify | check --repo <o/r> --issue <n> | sweep [--owners a,b] [--hours 3]");
    process.exit(2);
  }
  Promise.resolve(run(rest)).catch((e) => {
    console.error(e.message);
    process.exit(1);
  });
}
