#!/usr/bin/env node
// Writes orchestration/release-consumers.json from clones: node scripts/gen-release-consumers.mjs <folder of clones>
// (the check is `node scripts/krizaka-release.mjs check <folder>`). The repositories are the ones that consume @krizaka/*.
import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CONSUMERS_FILE, readDependencies } from "./krizaka-release.mjs";

const REPOS = [
  "akinaza", "yomizaka", "orazaka-web-client", "krizaka-com", "krizaka-blog", "krizaka-motion", "krizaka-build", "krizaka-ui", "krizaka-ts",
];
const about =
  "The repositories that depend on @krizaka/* packages and learn of a release by repository_dispatch (krizaka/.github#388). " +
  "Each lists the @krizaka/* packages it depends on, outside its own workspace. Generated by scripts/gen-release-consumers.mjs; " +
  "checked by `node scripts/krizaka-release.mjs check <folder of clones>`. The paused products wait on Dependabot until they resume.";

const clones = process.argv[2];
if (!clones) throw new Error("Usage: gen-release-consumers.mjs <folder of clones>");
const repos = {};
for (const repo of REPOS) {
  const dir = join(clones, repo);
  if (!existsSync(dir)) throw new Error(`${dir} is missing`);
  repos[repo] = readDependencies(dir);
}
writeFileSync(CONSUMERS_FILE, `${JSON.stringify({ _about: about, repos }, null, 2)}\n`);
