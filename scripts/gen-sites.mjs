#!/usr/bin/env node
// Writes orchestration/sites.json, the site repositories the site rules judge (krizaka-internal#3783):
//   node scripts/gen-sites.mjs <krizaka-ts clone> [<path of deploy/apps.json>]
// A site is generated, never typed: the repository of a `krizaka` or `open-source` entry of the `family` of @krizaka/org
// (packages/org/src/org.ts), plus the repository of every `*-coming-soon` app of deploy/apps.json (the sites that are not in the family yet).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const SITE_GROUPS = ["krizaka", "open-source"];
const ROW = /\[\s*"[\w-]+",\s*"[^"]*",\s*"[^"]*",\s*"([\w-]+)",\s*"[\w-]+",\s*[^,]+,\s*(?:gh\("([\w.-]+)"\)|null)\s*\]/g;
const about =
  "The site repositories that the conformance site rules (site-kit-current, site-no-raw-colour, site-bird-from-org) judge. " +
  "Generated by scripts/gen-sites.mjs from the family of @krizaka/org and deploy/apps.json (krizaka-internal#3783).";

/** The site repositories from the text of org.ts and the parsed deploy/apps.json, sorted. */
export function sitesOf(orgSource, appsJson) {
  const block = /FAMILY_ROWS[^=]*=\s*\[([\s\S]*?)\n\];/.exec(orgSource)?.[1];
  if (!block) throw new Error("FAMILY_ROWS not found in org.ts");
  const family = [...block.matchAll(ROW)].filter((m) => SITE_GROUPS.includes(m[1]) && m[2]).map((m) => m[2]);
  const comingSoon = appsJson.apps.filter((a) => a.app.endsWith("-coming-soon")).map((a) => a.repo.replace(/^krizaka\//, ""));
  return [...new Set([...family, ...comingSoon])].sort();
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [ts, appsPath = new URL("../deploy/apps.json", import.meta.url).pathname] = process.argv.slice(2);
  if (!ts) throw new Error("Usage: gen-sites.mjs <krizaka-ts clone> [deploy/apps.json]");
  const repos = sitesOf(readFileSync(join(ts, "packages/org/src/org.ts"), "utf8"), JSON.parse(readFileSync(appsPath, "utf8")));
  writeFileSync(new URL("../orchestration/sites.json", import.meta.url), `${JSON.stringify({ _about: about, repos }, null, 2)}\n`);
}
