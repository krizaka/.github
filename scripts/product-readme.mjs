#!/usr/bin/env node
/**
 * Generate and verify managed blocks in a Krizaka product README.
 *
 * Pure rendering and validation helpers are exported for tests; the CLI runs
 * only when this file is executed directly.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { MARKS_CDN, statusLabel } from "./profile-readme.mjs";

const DEFAULT_COLOUR = "3e76a8";
const DEFAULT_REGISTRY = fileURLToPath(new URL("../profile/products.json", import.meta.url));
const DEFAULT_README = "README.md";
const DEFAULT_SCHEMA = "docs/architecture/c1.mmd";

export const FSL_LINE = "FSL-1.1-ALv2: source-available, each release becomes Apache-2.0 two years later";
export const SECTIONS = ["Quick start", "Details"];
export const BLOCKS = ["head", "badges", "footer"];

function markersFor(name) {
  return {
    start: `<!-- product-readme:${name}:start — generated by krizaka/.github scripts/product-readme.mjs; do not edit -->`,
    end: `<!-- product-readme:${name}:end -->`,
  };
}

function wrapBlock(name, body) {
  const { start, end } = markersFor(name);
  return `${start}\n${body}\n${end}`;
}

function findBlock(readme, name) {
  const startRe = new RegExp(`<!--\\s*product-readme:${name}:start(?:\\s[^>]*)?-->`);
  const match = startRe.exec(readme);
  if (!match) return null;
  const { end } = markersFor(name);
  const endIndex = readme.indexOf(end, match.index + match[0].length);
  if (endIndex === -1) return null;
  return { from: match.index, to: endIndex + end.length };
}

function findHeading(readme, section) {
  const escaped = section.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = new RegExp(`^## ${escaped}\\s*$`, "m").exec(readme);
  return match ? match.index : -1;
}

function encodeBadgePart(text) {
  return encodeURIComponent(text.replace(/-/g, "--").replace(/_/g, "__"));
}

export function renderSchema(path, text) {
  if (typeof path === "string" && path.endsWith(".mmd")) {
    if (typeof text !== "string" || text.trim() === "") {
      throw new Error("Empty or missing Mermaid schema");
    }
    return `\`\`\`mermaid\n${text.trim()}\n\`\`\``;
  }
  if (typeof path !== "string" || path.trim() === "") {
    throw new Error("Empty or missing schema path");
  }
  return `![Architecture (C1)](${path})`;
}

function renderHead(data, id, product, schemaBlock) {
  const colour = String(product.colour || DEFAULT_COLOUR).replace(/^#/, "");
  const label = statusLabel(data, product);
  const body = [
    "<picture>",
    `  <source media="(prefers-color-scheme: dark)" srcset="${MARKS_CDN}/${id}/mark-dark.svg">`,
    `  <img src="${MARKS_CDN}/${id}/mark-light.svg" alt="${product.name}" width="48">`,
    "</picture>",
    "",
    `# ${product.name}`,
    "",
    `> ${product.proof}`,
    "",
    `**${product.knowhow}** · ![${label}](https://img.shields.io/badge/${encodeBadgePart(label)}-${colour})`,
    "",
    schemaBlock,
  ].join("\n");
  return wrapBlock("head", body);
}

function renderBadges(org, repo) {
  const base = `https://github.com/${org}/${repo}/actions/workflows`;
  const body = [
    `[![CI](${base}/ci.yml/badge.svg)](${base}/ci.yml)`,
    `[![Security](${base}/security.yml/badge.svg)](${base}/security.yml)`,
    "[![Licence](https://img.shields.io/badge/licence-FSL--1.1--ALv2-blue)](LICENSE)",
  ].join("\n");
  return wrapBlock("badges", body);
}

function renderFooter(org) {
  const body = [
    "---",
    "",
    FSL_LINE,
    "",
    `[Part of the Krizaka family of products](https://github.com/${org})`,
  ].join("\n");
  return wrapBlock("footer", body);
}

export function renderBlocks(data, id, { schema, schemaPath } = {}) {
  const product = data?.products?.[id];
  if (!product) {
    throw new Error(`Unknown product "${id}"`);
  }
  const schemaBlock = renderSchema(schemaPath || DEFAULT_SCHEMA, schema);
  const org = data.organization;
  const repo = product.repo ?? id;
  return {
    head: renderHead(data, id, product, schemaBlock),
    badges: renderBadges(org, repo),
    footer: renderFooter(org),
  };
}

export function applyBlocks(readme, blocks) {
  let result = readme;
  for (const name of BLOCKS) {
    if (!(name in blocks)) continue;
    const span = findBlock(result, name);
    if (!span) continue;
    result = result.slice(0, span.from) + blocks[name] + result.slice(span.to);
  }
  return result;
}

export function problemsOf(readme, blocks) {
  const problems = [];
  const spans = {};
  for (const name of BLOCKS) {
    const span = findBlock(readme, name);
    spans[name] = span;
    if (!span) {
      problems.push(`${name} block is missing`);
    } else if (readme.slice(span.from, span.to) !== blocks[name]) {
      problems.push(`${name} block is stale: run node scripts/product-readme.mjs`);
    }
  }
  const headings = {};
  for (const section of SECTIONS) {
    const index = findHeading(readme, section);
    headings[section] = index;
    if (index === -1) {
      problems.push(`section « ${section} » is missing`);
    }
  }
  if (spans.head && readme.slice(0, spans.head.from).trim().length > 0) {
    problems.push("head block must be first");
  }
  if (spans.badges) {
    const quickStart = headings["Quick start"];
    const details = headings["Details"];
    const beforeQuickStart = quickStart !== -1 && spans.badges.from < quickStart;
    const afterDetails = details !== -1 && spans.badges.from > details;
    if (beforeQuickStart || afterDetails) {
      problems.push("the badges go after the quick start");
    }
  }
  if (spans.footer && readme.slice(spans.footer.to).trim().length > 0) {
    problems.push("footer block must be last");
  }
  return problems;
}

function parseCliArgs(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      product: { type: "string" },
      registry: { type: "string", default: DEFAULT_REGISTRY },
      readme: { type: "string", default: DEFAULT_README },
      schema: { type: "string", default: DEFAULT_SCHEMA },
      check: { type: "boolean", default: false },
      print: { type: "boolean", default: false },
    },
    strict: true,
  });
  if (!values.product) {
    throw new Error("Missing required option: --product <id>");
  }
  return values;
}

function loadSchemaInput(schemaArg, cwd) {
  const fullPath = resolve(cwd, schemaArg);
  if (!existsSync(fullPath)) {
    return { error: `schema file is missing: ${schemaArg}` };
  }
  if (!schemaArg.endsWith(".mmd")) {
    return { schemaPath: schemaArg };
  }
  const text = readFileSync(fullPath, "utf8");
  if (text.trim() === "") {
    return { error: `schema file is empty: ${schemaArg}` };
  }
  return { schema: text, schemaPath: schemaArg };
}

function writeErrors(messages, asAnnotation) {
  const prefix = asAnnotation ? "::error::" : "product-readme: ";
  for (const message of messages) {
    process.stderr.write(`${prefix}${message}\n`);
  }
}

function runCheck(readmePath, blocks) {
  if (!existsSync(readmePath)) {
    writeErrors([`README not found: ${readmePath}`], true);
    return 1;
  }
  const readme = readFileSync(readmePath, "utf8");
  const problems = problemsOf(readme, blocks);
  if (problems.length > 0) {
    writeErrors(problems, true);
    return 1;
  }
  process.stdout.write("product-readme: ok\n");
  return 0;
}

function runRewrite(readmePath, blocks) {
  if (!existsSync(readmePath)) {
    writeErrors([`README not found: ${readmePath}. Add the product-readme markers via the template.`], false);
    return 1;
  }
  const readme = readFileSync(readmePath, "utf8");
  const missing = BLOCKS.filter((name) => !findBlock(readme, name));
  if (missing.length > 0) {
    writeErrors([`missing block(s): ${missing.join(", ")}. Add the markers via the README template.`], false);
    return 1;
  }
  writeFileSync(readmePath, applyBlocks(readme, blocks), "utf8");
  return 0;
}

function main(argv = process.argv.slice(2)) {
  let opts;
  try {
    opts = parseCliArgs(argv);
  } catch (error) {
    writeErrors([error.message], argv.includes("--check"));
    process.exitCode = 1;
    return;
  }
  const cwd = process.cwd();
  const schemaInput = loadSchemaInput(opts.schema, cwd);
  if (schemaInput.error) {
    writeErrors([schemaInput.error], opts.check);
    process.exitCode = 1;
    return;
  }
  let blocks;
  try {
    const data = JSON.parse(readFileSync(resolve(cwd, opts.registry), "utf8"));
    blocks = renderBlocks(data, opts.product, schemaInput);
  } catch (error) {
    writeErrors([error.message], opts.check);
    process.exitCode = 1;
    return;
  }
  if (opts.print) {
    process.stdout.write(`${BLOCKS.map((name) => blocks[name]).join("\n\n")}\n`);
    return;
  }
  const readmePath = resolve(cwd, opts.readme);
  process.exitCode = opts.check ? runCheck(readmePath, blocks) : runRewrite(readmePath, blocks);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}

