// repos.json (krizaka/.github#113) against the naming checker, the standard and deploy/apps.json, and the generator's rules.
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { KINDS, buildRegistry, drift, kindOf, ownerOf, parseDeleted, parseStandard, serialize } from "../scripts/gen-repos.mjs";
import { isValidRepositoryName } from "../scripts/repository-names.mjs";

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const { repositories } = JSON.parse(read("repos.json"));
const standard = parseStandard(read("docs/standards/repositories.md"));
const apps = JSON.parse(read("deploy/apps.json"));

test("every name follows the naming checker, or the standard has decided its rename, fold, archive or pause", () => {
  for (const row of repositories) {
    if (row.name === ".github" || isValidRepositoryName(row.name)) continue;
    assert.match(row.status, /^(Rename|Fold into|Archive|Paused)\b/, `${row.name} breaks the standard and nothing is decided`);
  }
  for (const row of repositories.filter((r) => r.renameTo)) {
    assert.ok(isValidRepositoryName(row.renameTo), `${row.name} → ${row.renameTo} is outside the standard`);
    assert.ok(!repositories.some((r) => r.name === row.renameTo), `${row.renameTo} already exists`);
  }
});

test("one row per repository of the standard, sorted, with the registry's fields", () => {
  const names = repositories.map((row) => row.name);
  assert.deepEqual(names, [...new Set(names)].sort());
  for (const name of standard.keys()) assert.ok(names.includes(name), `${name} is in the standard, not in repos.json`);
  for (const row of repositories) {
    for (const key of ["name", "owner", "role", "team", "kind", "deploy", "archived", "visibility", "status"]) {
      assert.ok(key in row, `${row.name}: no ${key}`);
    }
    assert.ok(KINDS.includes(row.kind), `${row.name}: kind ${row.kind}`);
    assert.equal(row.owner, ownerOf(row.name));
  }
});

test("deploy targets are deploy/apps.json's, each on its repository", () => {
  const targets = repositories.flatMap((row) => row.deploy.map((app) => `krizaka/${row.name}:${app}`)).sort();
  assert.deepEqual(targets, apps.apps.map((app) => `${app.repo}:${app.app}`).sort());
});

test("kind: root files first, then topics, then the role", () => {
  assert.equal(kindOf({ name: "krizaka-billing", files: ["pom.xml"] }), "maven");
  assert.equal(kindOf({ name: "krizaka-infra", files: ["main.tf"] }), "iac");
  assert.equal(kindOf({ name: "krizaka-infra", files: [], role: "Shared infrastructure as code" }), "iac");
  assert.equal(kindOf({ name: "sovkora-worker-media", files: ["pyproject.toml"] }), "python");
  assert.equal(kindOf({ name: "krizaka-desktop", files: ["Cargo.toml"] }), "rust");
  assert.equal(kindOf({ name: "krizaka-ui", files: ["package.json"], topics: ["npm-package", "react"], deploy: ["krizaka-ui-site"] }), "npm");
  assert.equal(kindOf({ name: "krizaka-com", files: ["package.json", "next.config.ts"] }), "site");
  assert.equal(kindOf({ name: "folioviv", files: ["package.json"], topics: ["nextjs"] }), "app");
  assert.equal(kindOf({ name: "folioviv-mobile", files: ["package.json", "app.json"] }), "app");
  assert.equal(kindOf({ name: "krizaka-template-web", files: ["package.json"] }), "app");
  assert.equal(kindOf({ name: "krizaka-ts", files: ["package.json"] }), "npm");
  assert.equal(kindOf({ name: "verikora-mobile", files: [], role: "Mobile app" }), "app");
  assert.equal(kindOf({ name: "krizaka-billing", files: [], role: "Shared capability service" }), "none");
});

test("the generator keeps a private repository of the standard, and reports drift field by field", () => {
  const std = new Map([
    ["folioviv", { role: "Main product repository", status: "Complies", renameTo: null, foldInto: null }],
    ["krizaka-internal", { role: "Private issues and notes", status: "Complies", renameTo: null, foldInto: null }],
  ]);
  const next = buildRegistry({
    repositories: [{ name: "folioviv", archived: false, visibility: "public", topics: ["nextjs"] }],
    files: { folioviv: ["package.json"] },
    standard: std,
    apps: { apps: [{ app: "folioviv-dev", repo: "krizaka/folioviv" }] },
  });
  assert.deepEqual(next.map((r) => [r.name, r.kind, r.deploy, r.archived, r.visibility]), [
    ["folioviv", "app", ["folioviv-dev"], false, "public"],
    ["krizaka-internal", "none", [], null, "private"],
  ]);
  assert.deepEqual(drift(next, next), []);
  const archived = next.map((r) => (r.name === "folioviv" ? { ...r, archived: true } : r));
  assert.deepEqual(drift(next, archived), ["- `folioviv`: archived false → true"]);
  assert.deepEqual(drift(next, next.slice(1)), ["- `folioviv`: gone"]);
  assert.match(serialize(next), /^\{\n {2}"_": "Generated by scripts\/gen-repos\.mjs/);
});

test("a repository the standard records as deleted is no row, even while GitHub still lists it (ADR-029)", () => {
  const markdown = read("docs/standards/repositories.md");
  const deleted = parseDeleted(markdown);
  assert.ok(deleted.has("sovkora-engine") && deleted.has("sovkora-ui-kit"), [...deleted].join());
  for (const name of deleted) {
    assert.ok(!standard.has(name), `${name} is both current and deleted in the standard`);
    assert.ok(!repositories.some((r) => r.name === name), `repos.json still lists ${name}`);
  }
  assert.deepEqual(parseDeleted("## Current repository names\n\n| `a` | b | c |\n\n## Deleted on x\n\n| `old` | `a`, `x/` |\n"), new Set(["old"]));
  const next = buildRegistry({
    repositories: [{ name: "sovkora", archived: false, visibility: "public" }, { name: "sovkora-web", archived: false, visibility: "public" }],
    standard: new Map([["sovkora", { role: "Main product repository", status: "Complies", renameTo: null, foldInto: null }]]),
    apps: { apps: [] },
    deleted: new Set(["sovkora-web"]),
  });
  assert.deepEqual(next.map((r) => r.name), ["sovkora"]);
});

test("repos.json is what serialize() writes (never edited by hand)", () => {
  assert.equal(read("repos.json"), serialize(repositories));
});

test("weekly registry drift preserves generator failures through tee", () => {
  assert.match(read(".github/workflows/repos-registry.yml"), /shell: bash\n\s+run: node scripts\/gen-repos\.mjs --check \| tee -a "\$GITHUB_STEP_SUMMARY"/);
});
