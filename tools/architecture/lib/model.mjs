// The one module that talks to LikeC4 (ADR-027 § 2): the hand-written models are parsed here, with the org base
// (specification.c4, org.c4) and the generated systems, and the standard views are generated and laid out here. Swapping the
// parser is a change of this file only.
import { createHash } from "node:crypto";
import { fromSources } from "@likec4/language-services/node";

export const MODEL_DIR = "docs/architecture/";
export const BASE_FILES = ["specification.c4", "org.c4"];
const LIFECYCLE = ["planned", "retiring"];
const sha256 = (text) => createHash("sha256").update(text).digest("hex");
const byString = (a, b) => Number(a > b) - Number(a < b);
const quote = (text) => `'${String(text).replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;

/** The model files of a repository at its commit: `docs/architecture/**.c4`, sorted. */
export function modelFiles(files) {
  return [...files.keys()].filter((p) => p.startsWith(MODEL_DIR) && p.endsWith(".c4")).sort(byString).map((path) => ({ path, text: files.get(path), sha256: sha256(files.get(path)) }));
}

/** The org base, read from krizaka/.github's files: the specification and the org's own part. */
export function baseOf(files) {
  return BASE_FILES.map((name) => ({ path: `${MODEL_DIR}${name}`, text: files.get(`${MODEL_DIR}${name}`) ?? null })).map((f) => ({ ...f, sha256: f.text === null ? null : sha256(f.text) }));
}

/** The generated systems (never typed, § 4): one per family entry with a home, with its group tag, links and home. */
export function systemsDsl(systems) {
  const lines = ["// Generated by tools/architecture from @krizaka/org (ADR-027): never written by hand.", "model {"];
  for (const s of systems) {
    lines.push(
      `  ${s.id} = system ${quote(s.name)} {`,
      `    #${s.group}`,
      `    link ${s.url} ${quote("Site")}`,
      `    link https://github.com/krizaka/${s.home} ${quote("Repository")}`,
      `    metadata {`,
      `      home ${quote(s.home)}`,
      `      family ${quote(s.id)}`,
      `    }`,
      `  }`,
    );
  }
  lines.push("}");
  return lines.join("\n");
}

/** The standard views (§ 2), generated from the systems and which of them have an inside. */
export function viewsDsl(systems, withInside, sitesKind = "site") {
  const has = (id) => withInside.has(id);
  // The system, and everything that talks to it or to its inside (the relationships are lifted to the system).
  const around = (ids) => ids.map((id) => `    include ${id}, * -> ${id}, ${id} -> *`).join("\n");
  const inside = (ids) => ids.map((id) => `    include ${id}, ${id}.*`).join("\n");
  const of = (group) => systems.filter((s) => s.group === group).map((s) => s.id);
  const blocks = [];
  for (const s of systems) {
    blocks.push(`  view ${s.id}_c1 {\n    title ${quote(`${s.name} · C1`)}\n${around([s.id])}\n  }`);
    if (has(s.id)) blocks.push(`  view ${s.id}_c2 of ${s.id} {\n    title ${quote(`${s.name} · C2`)}\n    include *\n  }`);
  }
  const group = (id, title, ids, body) => (ids.length ? blocks.push(`  view ${id} {\n    title ${quote(title)}\n${body(ids)}\n  }`) : null);
  group("assets_c1", "Assets · C1", of("asset"), around);
  group("libraries_c1", "Libraries · C1", of("libraries"), around);
  group("libraries_c2", "Libraries · C2", of("libraries").filter(has), inside);
  group("sites_c1", "Static sites · C1", of("sites"), around);
  const siteSystems = of("sites").filter(has);
  blocks.push(`  view sites_c2 {\n    title ${quote("Static sites · C2")}\n${siteSystems.length ? `${inside(siteSystems)}\n` : ""}    include * where kind is ${sitesKind}\n  }`);
  blocks.push(`  view org_c1 {\n    title ${quote("Krizaka · C1")}\n    include *\n  }`);
  return `// Generated by tools/architecture (ADR-027): the standard views.\nviews {\n${blocks.join("\n")}\n}`;
}

const virtual = (repo, path) => `${repo}/${path}`;

/** The parser's errors, with the repository, the file and a 1-based line. */
function errorsOf(likec4) {
  return likec4.getErrors().map((e) => {
    const where = String(e.sourceFsPath ?? "").replace(/^\/workspace\//, "");
    const slash = where.indexOf("/");
    return { repo: where.slice(0, slash), path: where.slice(slash + 1), line: (e.line ?? 0) + 1, message: e.message };
  });
}

function elementOf(e) {
  const tags = [...e.tags].sort(byString);
  const metadata = e.$element.metadata ?? {};
  return {
    id: e.id,
    kind: e.kind,
    title: e.title,
    description: e.$element.description?.txt ?? e.$element.description ?? null,
    technology: e.technology ?? null,
    tags,
    lifecycle: LIFECYCLE.find((t) => tags.includes(t)) ?? "current",
    metadata,
    links: (e.links ?? []).map((l) => ({ url: l.url, title: l.title ?? null })),
  };
}

/** Parse a set of virtual files; the elements, the relationships and the errors. */
export async function parse(files, { layout = false } = {}) {
  const likec4 = await fromSources(Object.fromEntries(files.map((f) => [virtual(f.repo, f.path), f.text])));
  try {
    const model = await likec4.computedModel();
    const elements = [...model.elements()].map(elementOf).sort((a, b) => byString(a.id, b.id));
    const relations = [...model.relationships()].map((r) => ({ id: r.id, source: r.source.id, target: r.target.id, title: r.title ?? null, tags: [...r.tags].sort(byString) }));
    const views = layout ? await likec4.diagrams() : [];
    return { errors: errorsOf(likec4), elements, relations, views };
  } finally {
    await likec4.dispose();
  }
}

const SPEC_BLOCK = /^\s*specification\s*\{/m;

/**
 * A home's own check: its files parse with the org base and the generated systems, it writes no specification, and every
 * element it adds lives inside its own system. Returns { status: ok | missing | invalid, errors, files, elements }.
 */
export async function checkHome({ base, systems, known, home, system }) {
  const files = home.files;
  if (files.length === 0) return { status: "missing", errors: [], files, elements: [] };
  const problems = files.filter((f) => SPEC_BLOCK.test(f.text)).map((f) => ({ repo: home.repo, path: f.path, line: 1, message: "a home writes no specification: the org's is krizaka/.github docs/architecture/specification.c4" }));
  const parsed = await parse([...base, systems, ...files.map((f) => ({ ...f, repo: home.repo }))]);
  const own = parsed.elements.filter((e) => !known.has(e.id));
  for (const e of own.filter((x) => !x.id.startsWith(`${system}.`))) {
    problems.push({ repo: home.repo, path: files[0].path, line: 1, message: `« ${e.id} » is outside the system ${system}: a home writes only its own system's inside (extend ${system})` });
  }
  const errors = [...parsed.errors.filter((e) => e.repo === home.repo), ...problems];
  return { status: errors.length ? "invalid" : "ok", errors, files: files.map(({ path, sha256: hash }) => ({ path, sha256: hash })), elements: own, sources: files.map((f) => ({ ...f, repo: home.repo })) };
}
